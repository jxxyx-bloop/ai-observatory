/* Pick a starting language: an explicit earlier choice (shared with the landing
   page) wins, then the browser's preference if we happen to speak it, then
   English. Never guesses from anything but those two. */
function detect() {
  var saved = null;
  try { saved = localStorage.getItem("observatory-lang"); } catch (e) {}
  if (saved && T[saved]) return saved;

  var want = (navigator.languages || [navigator.language || "en"]).slice();
  for (var i = 0; i < want.length; i++) {
    var tag = String(want[i]);
    for (var j = 0; j < LOCALES.length; j++) {
      if (LOCALES[j][0].toLowerCase() === tag.toLowerCase()) return LOCALES[j][0];
    }
    var short = tag.split("-")[0].toLowerCase();
    // zh without a script tag: mainland/Singapore read simplified, everyone
    // else traditional. Getting this wrong is worse than defaulting, so the
    // region has to say so explicitly.
    if (short === "zh") return /hant|tw|hk|mo/i.test(tag) ? "zh-Hant" : "zh-Hans";
    if (short === "pt") return "pt-BR";
    if (short === "tl") return "fil";
    for (var m = 0; m < LOCALES.length; m++) {
      if (LOCALES[m][0].split("-")[0] === short) return LOCALES[m][0];
    }
  }
  return "en";
}

